import assert from 'node:assert/strict';
import {loadTs} from './load-typescript.mjs';
const {catalog,videoMap}=await loadTs('src/catalog.ts');
const {historyCoreVideos,historyCoreComplete,historyNumbers,historyEras,historySupplementVideos,numberedHistoryLecture}=await loadTs('src/navigation/history-study.ts');
assert.ok(historyCoreComplete,'Required lecture sequence 1–38 must be complete');
assert.deepEqual(historyNumbers,Array.from({length:38},(_,i)=>i+1));
assert.equal(historyCoreVideos.length,38);
assert.equal(new Set(historyCoreVideos.map(v=>v.id)).size,38);
assert.ok(historyCoreVideos.every((v,i)=>v.id===videoMap.get(v.id)?.id&&numberedHistoryLecture(v.title)===i+1));
assert.equal(historyEras.length,11);
assert.deepEqual(historyEras.flatMap(e=>e.videos.map(v=>v.id)),historyCoreVideos.map(v=>v.id));
for(const era of historyEras)assert.ok(era.videos.length>0&&era.videos.every(v=>/^【歴史】/.test(v.title)));
const core=new Set(historyCoreVideos.map(v=>v.id));
assert.ok(historySupplementVideos.every(v=>!core.has(v.id)));
assert.ok(historySupplementVideos.every(v=>!(/勉強法|緊急動画|告知|購入|お知らせ/.test(v.title))));
const source=catalog.series.filter(s=>s.subjectId==='japanese-history'&&s.channelId==='sakurara'&&/【歴史第[一二三]期】/.test(s.title));
assert.equal(source.length,3,'Three verified official history playlists');
assert.ok(historyCoreVideos.every(v=>source.some(s=>s.videoIds.includes(v.id))));
console.log('History curriculum: PASS, 38 numbered lectures / 11 eras / '+historySupplementVideos.length+' supplementary videos');
